    private fun tryLoadFromAsset(
        context: Context,
        version: String,
        bookIdx: Int,
        chapterIdx: Int,
        verseIdx: Int
    ): String? {
        val assetName = when (version) {
            "ara" -> "biblia_ara.json"
            "nvi" -> "biblia_nvi.json"
            "ntlh" -> "biblia_ntlh.json"
            "jfaal" -> "biblia.json"
            "bkj" -> "biblia_bkj.json"
            else -> "biblia.json"
        }

        return try {
            // Os assets do Flutter são empacotados em assets/flutter_assets/,
            // não na pasta assets/ do módulo Android.
            val path = "flutter_assets/assets/$assetName"
            val inputStream = context.assets.open(path)
            val reader = java.io.InputStreamReader(inputStream, Charsets.UTF_8)
            val books = com.google.gson.Gson().fromJson(reader, Array<Book>::class.java)
            reader.close()

            if (books != null && bookIdx < books.size) {
                val book = books[bookIdx]
                if (chapterIdx < book.chapters.size) {
                    val chapter = book.chapters[chapterIdx]
                    if (verseIdx < chapter.size) {
                        chapter[verseIdx]
                    } else null
                } else null
            } else null
        } catch (e: Exception) {
            null
        }
    }

